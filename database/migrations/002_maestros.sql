CREATE TABLE IF NOT EXISTS material_proveedores (
  material_id BIGINT NOT NULL REFERENCES materiales(id) ON DELETE CASCADE,
  proveedor_id BIGINT NOT NULL REFERENCES proveedores(id) ON DELETE RESTRICT,
  precio_ref NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(precio_ref>=0),
  plazo_entrega_dias INTEGER NOT NULL DEFAULT 0 CHECK(plazo_entrega_dias>=0),
  preferido BOOLEAN NOT NULL DEFAULT FALSE, PRIMARY KEY(material_id,proveedor_id)
);

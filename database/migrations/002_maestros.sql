CREATE TABLE IF NOT EXISTS reclamos_proveedor (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, proveedor_id BIGINT NOT NULL REFERENCES proveedores(id) ON DELETE RESTRICT,

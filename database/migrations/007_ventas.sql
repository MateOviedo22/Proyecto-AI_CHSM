-- I6: facturación interna numerada (no fiscal) y devoluciones de venta con reingreso al almacén.
CREATE SEQUENCE IF NOT EXISTS factura_numero_seq;
CREATE TABLE IF NOT EXISTS facturas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, numero TEXT NOT NULL UNIQUE, venta_id BIGINT NOT NULL UNIQUE REFERENCES ventas(id),
  cliente_id TEXT REFERENCES clientes(id), cliente_nombre TEXT NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  subtotal NUMERIC(14,2) NOT NULL CHECK(subtotal>=0), descuento NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(descuento>=0), total NUMERIC(14,2) NOT NULL CHECK(total>=0),
  estado TEXT NOT NULL DEFAULT 'Emitida' CHECK (estado IN ('Emitida','Anulada')), anulada_motivo TEXT NOT NULL DEFAULT '', anulada_en TIMESTAMPTZ,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id), version INTEGER NOT NULL DEFAULT 1
);
-- Facturas para las ventas ya registradas (conserva el historial y asigna numeración consecutiva por fecha).
INSERT INTO facturas(numero,venta_id,cliente_id,cliente_nombre,fecha,subtotal,descuento,total,usuario_id)
  SELECT 'FAC-'||lpad(nextval('factura_numero_seq')::text,6,'0'),v.id,v.cliente_id,v.cliente_nombre,v.fecha,v.subtotal,v.descuento,v.total,v.usuario_id
  FROM (SELECT * FROM ventas WHERE NOT EXISTS (SELECT 1 FROM facturas f WHERE f.venta_id=ventas.id) ORDER BY fecha,id) v;

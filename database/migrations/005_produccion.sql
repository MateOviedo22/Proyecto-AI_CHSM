-- I4: producción. Plan con detalle, órdenes con varios productos y firmas (elaborado/revisado/autorizado),
-- requisiciones base y adicionales justificadas, avances, control de calidad, lotes y cierre con desperdicio.
CREATE SEQUENCE IF NOT EXISTS plan_produccion_seq;
CREATE SEQUENCE IF NOT EXISTS orden_produccion_seq;
CREATE SEQUENCE IF NOT EXISTS requisicion_seq;
CREATE TABLE IF NOT EXISTS planes_produccion (
  id TEXT PRIMARY KEY, fecha DATE NOT NULL DEFAULT CURRENT_DATE, inicio DATE NOT NULL, fin DATE NOT NULL, CHECK(fin>=inicio),
  estado TEXT NOT NULL DEFAULT 'Borrador' CHECK (estado IN ('Borrador','Revisado','Autorizado','Cerrado','Cancelado')),
  notas TEXT NOT NULL DEFAULT '', elaborado_por BIGINT NOT NULL REFERENCES usuarios(id),
  revisado_por BIGINT REFERENCES usuarios(id), revisado_en TIMESTAMPTZ, autorizado_por BIGINT REFERENCES usuarios(id), autorizado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(), version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS plan_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plan_id TEXT NOT NULL REFERENCES planes_produccion(id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL REFERENCES productos(id), ficha_id BIGINT REFERENCES fichas_tecnicas(id), linea_id BIGINT REFERENCES lineas_produccion(id),
  cantidad INTEGER NOT NULL CHECK(cantidad>0), notas TEXT NOT NULL DEFAULT '', UNIQUE(plan_id,producto_id)
);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS fecha DATE NOT NULL DEFAULT CURRENT_DATE;
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS plan_id TEXT REFERENCES planes_produccion(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS linea_id BIGINT REFERENCES lineas_produccion(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS fuera_plan BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS justificacion TEXT NOT NULL DEFAULT '';
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS observaciones TEXT NOT NULL DEFAULT '';
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS elaborado_por BIGINT REFERENCES usuarios(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS revisado_por BIGINT REFERENCES usuarios(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS revisado_en TIMESTAMPTZ;
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS autorizado_por BIGINT REFERENCES usuarios(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS autorizado_en TIMESTAMPTZ;
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS almacen_materiales_id BIGINT REFERENCES almacenes(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS almacen_destino_id BIGINT REFERENCES almacenes(id);
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS fecha_inicio TIMESTAMPTZ;
ALTER TABLE ordenes_produccion ADD COLUMN IF NOT EXISTS fecha_cierre TIMESTAMPTZ;
CREATE TABLE IF NOT EXISTS orden_produccion_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_id TEXT NOT NULL REFERENCES ordenes_produccion(id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL REFERENCES productos(id), ficha_id BIGINT NOT NULL REFERENCES fichas_tecnicas(id), plan_detalle_id BIGINT REFERENCES plan_detalles(id),
  cantidad_planificada INTEGER NOT NULL CHECK(cantidad_planificada>0), cantidad_producida INTEGER NOT NULL DEFAULT 0 CHECK(cantidad_producida>=0),
  aprobada INTEGER NOT NULL DEFAULT 0 CHECK(aprobada>=0), rechazada INTEGER NOT NULL DEFAULT 0 CHECK(rechazada>=0),
  lote_id BIGINT REFERENCES lotes(id), CHECK(aprobada+rechazada<=cantidad_producida), UNIQUE(orden_id,producto_id)
);
CREATE TABLE IF NOT EXISTS requisiciones_material (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, orden_id TEXT NOT NULL REFERENCES ordenes_produccion(id),
  tipo TEXT NOT NULL CHECK (tipo IN ('Base','Adicional')), estado TEXT NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente','Aprobada','Entregada','Rechazada')),
  justificacion TEXT NOT NULL DEFAULT '', almacen_id BIGINT REFERENCES almacenes(id),
  solicitado_por BIGINT NOT NULL REFERENCES usuarios(id), solicitado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  aprobado_por BIGINT REFERENCES usuarios(id), aprobado_en TIMESTAMPTZ, entregado_por BIGINT REFERENCES usuarios(id), entregado_en TIMESTAMPTZ,
  version INTEGER NOT NULL DEFAULT 1, CHECK (tipo='Base' OR length(trim(justificacion))>0)
);
CREATE TABLE IF NOT EXISTS requisicion_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, requisicion_id BIGINT NOT NULL REFERENCES requisiciones_material(id) ON DELETE CASCADE,
  material_id BIGINT NOT NULL REFERENCES materiales(id), cantidad_teorica NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(cantidad_teorica>=0),
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), cantidad_entregada NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(cantidad_entregada>=0),
  cantidad_devuelta NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(cantidad_devuelta>=0 AND cantidad_devuelta<=cantidad_entregada), UNIQUE(requisicion_id,material_id)
);
CREATE TABLE IF NOT EXISTS produccion_registros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_detalle_id BIGINT NOT NULL REFERENCES orden_produccion_detalles(id) ON DELETE CASCADE,
  cantidad INTEGER NOT NULL CHECK(cantidad>0), etapa TEXT NOT NULL DEFAULT '', notas TEXT NOT NULL DEFAULT '',
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(), usuario_id BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS control_calidad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_detalle_id BIGINT NOT NULL REFERENCES orden_produccion_detalles(id) ON DELETE CASCADE,
  revisada INTEGER NOT NULL CHECK(revisada>0), aprobada INTEGER NOT NULL CHECK(aprobada>=0), rechazada INTEGER NOT NULL CHECK(rechazada>=0),
  observaciones TEXT NOT NULL DEFAULT '', defecto TEXT NOT NULL DEFAULT '', inspector_id BIGINT NOT NULL REFERENCES usuarios(id), fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK(aprobada+rechazada=revisada)
);
ALTER TABLE produccion_consumos ADD COLUMN IF NOT EXISTS lote_id BIGINT REFERENCES lotes(id);
ALTER TABLE produccion_consumos ADD COLUMN IF NOT EXISTS requisicion_id BIGINT REFERENCES requisiciones_material(id);
ALTER TABLE produccion_consumos ADD COLUMN IF NOT EXISTS tipo TEXT NOT NULL DEFAULT 'Entrega' CHECK (tipo IN ('Entrega','Devolución'));
-- Resumen al cierre: consumo teórico (ficha × producido) frente a real (entregado − devuelto) y desperdicio.
CREATE TABLE IF NOT EXISTS produccion_resumen_materiales (
  orden_id TEXT NOT NULL REFERENCES ordenes_produccion(id) ON DELETE CASCADE, material_id BIGINT NOT NULL REFERENCES materiales(id),
  teorico NUMERIC(14,3) NOT NULL DEFAULT 0, entregado NUMERIC(14,3) NOT NULL DEFAULT 0, devuelto NUMERIC(14,3) NOT NULL DEFAULT 0,
  consumo_real NUMERIC(14,3) NOT NULL DEFAULT 0, desperdicio NUMERIC(14,3) NOT NULL DEFAULT 0, costo_unitario NUMERIC(14,2) NOT NULL DEFAULT 0,
  PRIMARY KEY(orden_id,material_id)
);
CREATE INDEX IF NOT EXISTS idx_opd_orden ON orden_produccion_detalles(orden_id);
CREATE INDEX IF NOT EXISTS idx_consumos_orden ON produccion_consumos(orden_id);
CREATE INDEX IF NOT EXISTS idx_requisiciones_orden ON requisiciones_material(orden_id);

INSERT INTO almacenes(codigo,nombre,ubicacion,tipo,descripcion) VALUES
 ('ALM-TALLER','Taller de producción','Taller','Taller','Materia prima, insumos y producto en proceso'),
 ('ALM-TIENDA','Tienda / Sucursal','Sucursal','Tienda','Producto terminado disponible para venta')
ON CONFLICT (codigo) DO NOTHING;

CREATE SEQUENCE IF NOT EXISTS lote_codigo_seq;
CREATE TABLE IF NOT EXISTS lotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo TEXT NOT NULL UNIQUE,
  producto_id BIGINT REFERENCES productos(id) ON DELETE RESTRICT, material_id BIGINT REFERENCES materiales(id) ON DELETE RESTRICT,
  origen TEXT NOT NULL CHECK (origen IN ('Compra','Producción','Ajuste','Inicial')), referencia TEXT NOT NULL DEFAULT '',
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(), vencimiento DATE, notas TEXT NOT NULL DEFAULT '',
  CHECK ((producto_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
CREATE TABLE IF NOT EXISTS existencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, almacen_id BIGINT NOT NULL REFERENCES almacenes(id) ON DELETE RESTRICT,
  producto_id BIGINT REFERENCES productos(id) ON DELETE RESTRICT, material_id BIGINT REFERENCES materiales(id) ON DELETE RESTRICT,
  lote_id BIGINT REFERENCES lotes(id) ON DELETE RESTRICT, cantidad NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(cantidad>=0),
  minimo NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(minimo>=0), actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((producto_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_existencias_unica ON existencias(almacen_id,COALESCE(producto_id,0),COALESCE(material_id,0),COALESCE(lote_id,0));
CREATE INDEX IF NOT EXISTS idx_existencias_producto ON existencias(producto_id) WHERE producto_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_existencias_material ON existencias(material_id) WHERE material_id IS NOT NULL;
-- Mínimo por almacén y artículo (independiente del lote).
CREATE TABLE IF NOT EXISTS minimos_almacen (
  almacen_id BIGINT NOT NULL REFERENCES almacenes(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES productos(id) ON DELETE CASCADE, material_id BIGINT REFERENCES materiales(id) ON DELETE CASCADE,
  minimo NUMERIC(14,3) NOT NULL CHECK(minimo>=0),
  CHECK ((producto_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_minimos_almacen ON minimos_almacen(almacen_id,COALESCE(producto_id,0),COALESCE(material_id,0));


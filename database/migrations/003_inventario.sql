  SELECT a.id,m.id,m.existencia FROM materiales m CROSS JOIN almacenes a
  WHERE a.codigo='ALM-TALLER' AND m.existencia>0 AND NOT EXISTS (SELECT 1 FROM existencias e WHERE e.material_id=m.id);
INSERT INTO existencias(almacen_id,producto_id,cantidad)
  SELECT a.id,p.id,p.existencia FROM productos p CROSS JOIN almacenes a
  WHERE a.codigo='ALM-TIENDA' AND p.existencia>0 AND NOT EXISTS (SELECT 1 FROM existencias e WHERE e.producto_id=p.id);

-- I5: traslados entre almacenes (taller, tienda y otros) con formulario formal, firmas, estados,
-- despacho/recepción por lote, diferencias y evidencias adjuntas.
CREATE SEQUENCE IF NOT EXISTS traslado_seq;
CREATE TABLE IF NOT EXISTS traslados (
  id TEXT PRIMARY KEY, fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  origen_id BIGINT NOT NULL REFERENCES almacenes(id), destino_id BIGINT NOT NULL REFERENCES almacenes(id), CHECK(origen_id<>destino_id),
  motivo TEXT NOT NULL CHECK (motivo IN ('Reabastecimiento de tienda','Devolución a taller','Producto defectuoso','Reubicación','Exhibición o evento','Otro')),
  estado TEXT NOT NULL DEFAULT 'Borrador' CHECK (estado IN ('Borrador','Revisado','Autorizado','En tránsito','Recibido','Recibido con diferencias','Cancelado')),
  observaciones TEXT NOT NULL DEFAULT '', fecha_requerida DATE,
  elaborado_por BIGINT NOT NULL REFERENCES usuarios(id), elaborado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  revisado_por BIGINT REFERENCES usuarios(id), revisado_en TIMESTAMPTZ, autorizado_por BIGINT REFERENCES usuarios(id), autorizado_en TIMESTAMPTZ,
  despachado_por BIGINT REFERENCES usuarios(id), despachado_en TIMESTAMPTZ, recibido_por BIGINT REFERENCES usuarios(id), recibido_en TIMESTAMPTZ,
  cancelado_motivo TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS traslado_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, traslado_id TEXT NOT NULL REFERENCES traslados(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES productos(id), material_id BIGINT REFERENCES materiales(id), lote_id BIGINT REFERENCES lotes(id),
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), cantidad_recibida NUMERIC(14,3) CHECK(cantidad_recibida>=0 AND cantidad_recibida<=cantidad),
  diferencia_motivo TEXT NOT NULL DEFAULT '', CHECK ((producto_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
-- Lotes efectivamente despachados por línea (FIFO cuando no se indicó lote) para reingresarlos en el destino.
CREATE TABLE IF NOT EXISTS traslado_despachos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, traslado_detalle_id BIGINT NOT NULL REFERENCES traslado_detalles(id) ON DELETE CASCADE,
  lote_id BIGINT REFERENCES lotes(id), cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), recibido NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(recibido>=0 AND recibido<=cantidad)
);
CREATE TABLE IF NOT EXISTS traslado_evidencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, traslado_id TEXT NOT NULL REFERENCES traslados(id) ON DELETE CASCADE,
  etapa TEXT NOT NULL CHECK (etapa IN ('Preparación','Despacho','Recepción','Otro')), nombre TEXT NOT NULL, tipo TEXT NOT NULL CHECK (tipo IN ('image/jpeg','image/png','application/pdf')),
  tamano INTEGER NOT NULL CHECK(tamano>0 AND tamano<=2097152), contenido BYTEA NOT NULL, descripcion TEXT NOT NULL DEFAULT '',
  subido_por BIGINT NOT NULL REFERENCES usuarios(id), fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_traslado_detalles ON traslado_detalles(traslado_id);
CREATE INDEX IF NOT EXISTS idx_traslado_evidencias ON traslado_evidencias(traslado_id);

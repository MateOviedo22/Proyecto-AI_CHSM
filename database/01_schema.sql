-- Sunshine ERP/CRM: PostgreSQL 15+. Initial schema; review before applying to existing data.
BEGIN;
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL, usuario TEXT NOT NULL UNIQUE, correo TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL, rol TEXT NOT NULL DEFAULT 'operador' CHECK (rol IN ('admin','operador')),
  activo BOOLEAN NOT NULL DEFAULT TRUE, creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS clientes (
  id TEXT PRIMARY KEY, nombre TEXT NOT NULL CHECK(length(trim(nombre))>0), tipo TEXT NOT NULL DEFAULT 'Ocasional',
  correo TEXT NOT NULL DEFAULT '', telefono TEXT NOT NULL DEFAULT '', ubicacion TEXT NOT NULL DEFAULT '',
  estado TEXT NOT NULL DEFAULT 'Activo', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS proveedores (
  id BIGINT PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL CHECK(length(trim(nombre))>0),
  contacto TEXT NOT NULL DEFAULT '', telefono TEXT NOT NULL DEFAULT '', correo TEXT NOT NULL DEFAULT '',
  direccion TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Activo', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS materiales (
  id BIGINT PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL CHECK(length(trim(nombre))>0),
  tipo TEXT NOT NULL DEFAULT 'Materia prima', categoria TEXT NOT NULL DEFAULT 'Otro', unidad TEXT NOT NULL DEFAULT 'unidad',
  existencia NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(existencia>=0), minimo NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(minimo>=0),
  costo NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(costo>=0), ubicacion TEXT NOT NULL DEFAULT '', proveedor TEXT NOT NULL DEFAULT '',
  version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS productos (
  id BIGINT PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL CHECK(length(trim(nombre))>0),
  categoria TEXT NOT NULL DEFAULT 'Otros', precio NUMERIC(14,2) NOT NULL CHECK(precio>=0),
  existencia INTEGER NOT NULL DEFAULT 0 CHECK(existencia>=0), minimo INTEGER NOT NULL DEFAULT 0 CHECK(minimo>=0),
  descripcion TEXT NOT NULL DEFAULT '', material TEXT NOT NULL DEFAULT '', activo BOOLEAN NOT NULL DEFAULT TRUE,
  version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id TEXT REFERENCES clientes(id) ON DELETE RESTRICT,
  cliente_nombre TEXT NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT now(), metodo TEXT NOT NULL,
  subtotal NUMERIC(14,2) NOT NULL CHECK(subtotal>=0), descuento NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(descuento>=0),
  total NUMERIC(14,2) NOT NULL CHECK(total>=0), usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  estado TEXT NOT NULL DEFAULT 'Completada'
);
CREATE TABLE IF NOT EXISTS venta_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_id BIGINT NOT NULL REFERENCES ventas(id) ON DELETE RESTRICT,
  producto_id BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT, cantidad INTEGER NOT NULL CHECK(cantidad>0),
  precio NUMERIC(14,2) NOT NULL CHECK(precio>=0), subtotal NUMERIC(14,2) NOT NULL CHECK(subtotal>=0),
  UNIQUE(venta_id,producto_id)
);
CREATE TABLE IF NOT EXISTS movimientos_inventario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, producto_id BIGINT REFERENCES productos(id) ON DELETE RESTRICT,
  material_id BIGINT REFERENCES materiales(id) ON DELETE RESTRICT, tipo TEXT NOT NULL,
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad<>0), saldo NUMERIC(14,3) NOT NULL CHECK(saldo>=0),
  referencia TEXT NOT NULL DEFAULT '', usuario_id BIGINT NOT NULL REFERENCES usuarios(id), fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((producto_id IS NOT NULL)::int + (material_id IS NOT NULL)::int = 1)
);
CREATE TABLE IF NOT EXISTS entradas_material (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, material_id BIGINT NOT NULL REFERENCES materiales(id),
  fecha DATE NOT NULL, proveedor TEXT NOT NULL DEFAULT '', cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0),
  costo_unitario NUMERIC(14,2) NOT NULL CHECK(costo_unitario>=0), documento TEXT NOT NULL DEFAULT '',
  notas TEXT NOT NULL DEFAULT '', usuario_id BIGINT NOT NULL REFERENCES usuarios(id), creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS ordenes_produccion (
  id TEXT PRIMARY KEY, producto TEXT NOT NULL CHECK(length(trim(producto))>0), cantidad INTEGER NOT NULL CHECK(cantidad>0),
  prioridad TEXT NOT NULL DEFAULT 'Media', fecha_entrega DATE, responsable TEXT NOT NULL DEFAULT '',
  estado TEXT NOT NULL DEFAULT 'Pendiente', etapa TEXT NOT NULL DEFAULT 'Diseño y patronaje',
  progreso INTEGER NOT NULL DEFAULT 0 CHECK(progreso BETWEEN 0 AND 100), version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS etapas_produccion (
  id BIGINT PRIMARY KEY, nombre TEXT NOT NULL, descripcion TEXT NOT NULL DEFAULT '',
  responsable TEXT NOT NULL DEFAULT '', duracion TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Activa', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS empleados (
  id BIGINT PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL, puesto TEXT NOT NULL DEFAULT '', area TEXT NOT NULL DEFAULT '',
  telefono TEXT NOT NULL DEFAULT '', contratacion DATE, estado TEXT NOT NULL DEFAULT 'Activo', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS cargos (
  id BIGINT PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, area TEXT NOT NULL, puesto TEXT NOT NULL,
  plazas INTEGER NOT NULL DEFAULT 0 CHECK(plazas>=0), estado TEXT NOT NULL DEFAULT 'Activo', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS asistencias (
  id BIGINT PRIMARY KEY, empleado TEXT NOT NULL, fecha DATE NOT NULL, entrada TEXT NOT NULL DEFAULT '', salida TEXT NOT NULL DEFAULT '',
  horario TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Presente', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS ausencias (
  id BIGINT PRIMARY KEY, empleado TEXT NOT NULL, tipo TEXT NOT NULL, inicio DATE NOT NULL, fin DATE NOT NULL,
  motivo TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Pendiente', version INTEGER NOT NULL DEFAULT 1, CHECK(fin>=inicio)
);
CREATE TABLE IF NOT EXISTS finanzas_movimientos (
  id BIGINT PRIMARY KEY, tipo TEXT NOT NULL CHECK(tipo IN ('Ingreso','Gasto')),
  fecha DATE NOT NULL, concepto TEXT NOT NULL, categoria TEXT NOT NULL DEFAULT '', monto NUMERIC(14,2) NOT NULL CHECK(monto>=0),
  metodo TEXT NOT NULL DEFAULT '', proveedor TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Pendiente',
  venta_id BIGINT UNIQUE REFERENCES ventas(id), version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS cuentas_financieras (
  id BIGINT PRIMARY KEY, tipo TEXT NOT NULL CHECK(tipo IN ('Cobrar','Pagar')), contraparte TEXT NOT NULL,
  documento TEXT NOT NULL, fecha DATE NOT NULL, vencimiento DATE NOT NULL, monto NUMERIC(14,2) NOT NULL CHECK(monto>=0),
  abonado NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(abonado>=0 AND abonado<=monto), estado TEXT NOT NULL DEFAULT 'Pendiente',
  version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS crm_actividades (
  id BIGINT PRIMARY KEY, cliente TEXT NOT NULL, tipo TEXT NOT NULL, titulo TEXT NOT NULL, descripcion TEXT NOT NULL DEFAULT '',
  fecha DATE NOT NULL, hora TEXT NOT NULL DEFAULT '', responsable TEXT NOT NULL DEFAULT '', estado TEXT NOT NULL DEFAULT 'Pendiente',
  version INTEGER NOT NULL DEFAULT 1
);
-- Relational structures for workflows that still need frontend integration.
CREATE TABLE IF NOT EXISTS solicitudes_compra (
  id TEXT PRIMARY KEY, material_id BIGINT REFERENCES materiales(id), solicitante TEXT NOT NULL,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE, cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), estado TEXT NOT NULL DEFAULT 'Pendiente',
  area TEXT NOT NULL DEFAULT '', unidad TEXT NOT NULL DEFAULT '', prioridad TEXT NOT NULL DEFAULT 'Media', observaciones TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS ordenes_compra (
  id TEXT PRIMARY KEY, solicitud_id TEXT REFERENCES solicitudes_compra(id), proveedor_id BIGINT REFERENCES proveedores(id),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE, fecha_entrega DATE, estado TEXT NOT NULL DEFAULT 'Borrador', usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS orden_compra_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_id TEXT NOT NULL REFERENCES ordenes_compra(id),
  material_id BIGINT NOT NULL REFERENCES materiales(id), cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0),
  precio NUMERIC(14,2) NOT NULL CHECK(precio>=0)
);
CREATE TABLE IF NOT EXISTS recepciones_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_detalle_id BIGINT NOT NULL REFERENCES orden_compra_detalles(id),
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), fecha TIMESTAMPTZ NOT NULL DEFAULT now(), documento TEXT NOT NULL DEFAULT '', observaciones TEXT NOT NULL DEFAULT '', usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS cotizaciones (
  id TEXT PRIMARY KEY, cliente_id TEXT REFERENCES clientes(id), cliente_nombre TEXT NOT NULL,
  fecha DATE NOT NULL, vencimiento DATE NOT NULL, estado TEXT NOT NULL DEFAULT 'Pendiente', notas TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS cotizacion_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cotizacion_id TEXT NOT NULL REFERENCES cotizaciones(id),
  producto_id BIGINT NOT NULL REFERENCES productos(id), cantidad INTEGER NOT NULL CHECK(cantidad>0), precio NUMERIC(14,2) NOT NULL CHECK(precio>=0)
);
CREATE TABLE IF NOT EXISTS ordenes_venta (
  id TEXT PRIMARY KEY, cotizacion_id TEXT NOT NULL UNIQUE REFERENCES cotizaciones(id), cliente_nombre TEXT NOT NULL,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE, estado TEXT NOT NULL DEFAULT 'Pendiente', notas TEXT NOT NULL DEFAULT '',
  version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS orden_venta_detalles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_id TEXT NOT NULL REFERENCES ordenes_venta(id),
  producto_id BIGINT NOT NULL REFERENCES productos(id), cantidad INTEGER NOT NULL CHECK(cantidad>0), precio NUMERIC(14,2) NOT NULL CHECK(precio>=0)
);
-- Additional relational model for modules whose screens are still prototypes.
CREATE TABLE IF NOT EXISTS almacenes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL, ubicacion TEXT NOT NULL DEFAULT '', activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS fichas_tecnicas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, producto_id BIGINT NOT NULL REFERENCES productos(id), nombre TEXT NOT NULL,
  tiempo_minutos INTEGER NOT NULL DEFAULT 0 CHECK(tiempo_minutos>=0), notas TEXT NOT NULL DEFAULT '', activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS ficha_materiales (
  ficha_id BIGINT NOT NULL REFERENCES fichas_tecnicas(id), material_id BIGINT NOT NULL REFERENCES materiales(id),
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), PRIMARY KEY(ficha_id,material_id)
);
CREATE TABLE IF NOT EXISTS produccion_consumos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, orden_id TEXT NOT NULL REFERENCES ordenes_produccion(id),
  material_id BIGINT NOT NULL REFERENCES materiales(id), cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), fecha TIMESTAMPTZ NOT NULL DEFAULT now(), usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS promociones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre TEXT NOT NULL, producto_id BIGINT NOT NULL REFERENCES productos(id),
  tipo TEXT NOT NULL CHECK(tipo IN ('porcentaje','fijo')), valor NUMERIC(14,2) NOT NULL CHECK(valor>=0), inicio DATE NOT NULL, fin DATE NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT FALSE, version INTEGER NOT NULL DEFAULT 1, CHECK(fin>=inicio), CHECK(tipo<>'porcentaje' OR valor<=100)
);
CREATE TABLE IF NOT EXISTS devoluciones_venta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, venta_detalle_id BIGINT NOT NULL REFERENCES venta_detalles(id),
  cantidad INTEGER NOT NULL CHECK(cantidad>0), motivo TEXT NOT NULL, estado TEXT NOT NULL DEFAULT 'Pendiente', fecha TIMESTAMPTZ NOT NULL DEFAULT now(), usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS devoluciones_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recepcion_id BIGINT NOT NULL REFERENCES recepciones_compra(id),
  cantidad NUMERIC(14,3) NOT NULL CHECK(cantidad>0), motivo TEXT NOT NULL, estado TEXT NOT NULL DEFAULT 'Pendiente', fecha TIMESTAMPTZ NOT NULL DEFAULT now(), usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id BIGINT REFERENCES usuarios(id),
  accion TEXT NOT NULL, recurso TEXT NOT NULL, registro TEXT, fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_solicitud_orden_activa ON ordenes_compra(solicitud_id) WHERE solicitud_id IS NOT NULL AND estado <> 'Cancelada';
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas(fecha);
CREATE INDEX IF NOT EXISTS idx_inventario_producto ON movimientos_inventario(producto_id,fecha);
CREATE INDEX IF NOT EXISTS idx_inventario_material ON movimientos_inventario(material_id,fecha);
COMMIT;
